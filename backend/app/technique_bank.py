def flat_topics(categories: list[str] | None = None) -> list[str]:
    cats = categories or list(MASTER_TECHNIQUE_BANK.keys())
    out: list[str] = []
    for cat in cats:
        out.extend(MASTER_TECHNIQUE_BANK.get(cat, []))
    return out


def priority_topics() -> list[str]:
    return flat_topics(INTERVIEW_CONFIG["priority_categories"])


def _technique_weight(category: str, technique: str) -> float:
    cat_w = float(INTERVIEW_CONFIG["category_weights"].get(category, 1.0))
    tech_w = (
        float(INTERVIEW_CONFIG["high_technique_weight"])
        if technique in HIGH_WEIGHT_TECHNIQUES
        else float(INTERVIEW_CONFIG["default_technique_weight"])
    )
    return cat_w * tech_w


def sample_session_topics(
    n: int | None = None,
    *,
    rng: random.Random | None = None,
) -> list[dict[str, str]]:
    """First 6 = RAP core (fixed). Rest = weighted sample from related cats."""
    count = int(n or INTERVIEW_CONFIG["questions_per_session"])
    rng = rng or random.Random()

    core = [dict(t) for t in RAP_CORE_LLM_TOPICS]
    if count <= len(core):
        return core[:count]

    used = {(t["category"], t["technique"].lower()) for t in core}
    # Also block near-duplicates by technique keyword overlap with core titles
    core_needles = [
        "embedding",
        "latency",
        "throughput",
        "system prompt",
        "quantization",
        "temperature",
        "top-k",
        "top-p",
        "training vs inference",
        "hyperparameter",
    ]

    pool: list[tuple[str, str, float]] = []
    for cat in RAP_RELATED_CATEGORIES:
        techniques = MASTER_TECHNIQUE_BANK.get(cat, [])
        for tech in techniques:
            key = (cat, tech.lower())
            if key in used:
                continue
            low = tech.lower()
            if any(n in low for n in core_needles):
                # skip near-copies of the hardcoded six
                continue
            w = _technique_weight(cat, tech)
            pool.append((cat, tech, w))

    selected = list(core)
    remaining = list(pool)
    need = count - len(selected)
    for _ in range(min(need, len(remaining))):
        weights = [w for _, _, w in remaining]
        pick = rng.choices(range(len(remaining)), weights=weights, k=1)[0]
        cat, tech, _ = remaining.pop(pick)
        selected.append({"category": cat, "technique": tech})
        used.add((cat, tech.lower()))
    return selected


